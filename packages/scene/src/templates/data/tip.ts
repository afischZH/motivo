const LEFT = { h: "start" } as const;

/** A numbered row: a filled circle with the number and a text next to it, as one group. */
function step(
  b: Builder,
  n: number,
  y: number,
  o: { x: number; w: number; size: number; font: string; circle: number },
): Layer[] {
  const group = `step${n}`;
  return [
    b.ellipse({ id: `${group}-dot`, x: o.x, y, w: o.circle, h: o.circle, fill: "brand-2", group }),
    b.text({
      id: `${group}-n`,
      x: o.x,
      y: y + o.circle * 0.2,
      w: o.circle,
      h: o.circle * 0.6,
      role: "heading",
      font: o.font,
      size: o.circle * 0.5,
      lh: 1,
      align: "center",
      valign: "middle",
      color: "brand-5",
      group,
    }),
    b.text({
      id: `${group}-text`,
      x: o.x + o.circle + 30,
      y: y + o.circle * 0.12,
      w: o.w - o.circle - 30,
      h: o.circle * 1.4,
      role: "body",
      font: "inter",
      size: o.size,
      lh: 1.25,
      color: "brand-1",
      group,
    }),
  ];
}

