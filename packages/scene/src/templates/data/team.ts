/** Initials in a circle (stands in for a portrait), as one group. */
function avatar(b: Builder, id: string, x: number, y: number, d: number, font: string): Layer[] {
  return [
    b.ellipse({ id: `${id}-bg`, x, y, w: d, h: d, fill: "brand-2", group: id }),
    b.text({
      id,
      x: x + d * 0.1,
      y: y + d * 0.3,
      w: d * 0.8,
      h: d * 0.4,
      role: "heading",
      font,
      size: d * 0.34,
      lh: 1,
      align: "center",
      valign: "middle",
      color: "brand-5",
      group: id,
    }),
  ];
}

